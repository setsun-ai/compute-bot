def reader(d):
    return lambda f: K._read(d / f)


def plan_of(root, engine, **p):
    d = root / engine
    return K.plan(engine, (d / "README").read_text(), reader(d), params(**p),
                  K.ref_constants(d) if engine == "namd" else None)


