def peptide_atoms(nres=6):
    """A poly-Ala α-helix (N, HN, CA, CB, C, O; OT1/OT2 at the C end), 3 TIP3 waters, one SOD and one CLA."""
    atoms = []  # (segid, resid, resname, name, type, charge, mass, xyz)
    for i in range(nres):
        ang = math.radians(100.0 * i)
        z = 1.5 * i
        def at(r, dphi, dz, ang=ang, z=z):
            return (r * math.cos(ang + math.radians(dphi)), r * math.sin(ang + math.radians(dphi)), z + dz)
        names = [("N", "NH1", -0.47, 14.007, at(1.6, -28, -0.9)), ("HN", "H", 0.31, 1.008, at(1.2, -40, -1.6)),
                 ("CA", "CT1", 0.07, 12.011, at(2.3, 0, 0.0)), ("CB", "CT3", -0.27, 12.011, at(3.6, 5, 0.3)),
                 ("C", "C", 0.51, 12.011, at(1.6, 28, 0.9))]
        if i < nres - 1:
            names.append(("O", "O", -0.51, 15.999, at(1.9, 40, 2.0)))
        else:
            names += [("OT1", "OC", -0.67, 15.999, at(1.9, 40, 2.0)), ("OT2", "OC", -0.67, 15.999, at(1.1, 50, 1.4))]
        atoms += [("PROA", i + 1, "ALA", n, t, q, m, xyz) for n, t, q, m, xyz in names]
    for w in range(3):
        o = (8.0 + 3 * w, 8.0, 8.0)
        atoms += [("SOLV", w + 1, "TIP3", "OH2", "OT", -0.834, 15.9994, o),
                  ("SOLV", w + 1, "TIP3", "H1", "HT", 0.417, 1.008, (o[0] + 0.96, o[1], o[2])),
                  ("SOLV", w + 1, "TIP3", "H2", "HT", 0.417, 1.008, (o[0] - 0.24, o[1] + 0.93, o[2]))]
    atoms.append(("IONS", 1, "SOD", "SOD", "SOD", 1.0, 22.99, (-8.0, -8.0, 4.0)))
    atoms.append(("IONS", 2, "CLA", "CLA", "CLA", -1.0, 35.45, (-8.0, 8.0, 4.0)))
    return atoms


def bonds(atoms):
    index = {(a[0], a[1], a[3]): i + 1 for i, a in enumerate(atoms)}
    out = []
    for seg, resid, resn, name, *_ in atoms:
        key = index[(seg, resid, name)]
        if resn == "ALA":
            partner = {"HN": "N", "CA": "N", "CB": "CA", "C": "CA", "O": "C", "OT1": "C", "OT2": "C"}.get(name)
            if partner:
                out.append((index[(seg, resid, partner)], key))
            if name == "N" and resid > 1:
                out.append((index[(seg, resid - 1, "C")], key))
        elif resn == "TIP3" and name in ("H1", "H2"):
            out.append((index[(seg, resid, "OH2")], key))
    return out


def write_psf(path, atoms):
    lines = ["PSF CMAP CHEQ", "", "       1 !NTITLE", "* synthetic peptide in water", "", f"{len(atoms):8d} !NATOM"]
    for i, (seg, resid, resn, name, typ, q, m, _) in enumerate(atoms, 1):
        lines.append(f"{i:8d} {seg:<4s} {resid:<4d} {resn:<4s} {name:<4s} {typ:<4s} {q:14.6f}{m:14.6f}{0:8d}")
    b = bonds(atoms)
    lines += ["", f"{len(b):8d} !NBOND: bonds"]
    flat = [x for pair in b for x in pair]
    for k in range(0, len(flat), 8):
        lines.append("".join(f"{x:8d}" for x in flat[k:k + 8]))
    lines += ["", "       0 !NTHETA: angles", "", "", "       0 !NPHI: dihedrals", "", "",
              "       0 !NIMPHI: impropers", "", "", "       0 !NDON: donors", "", "", "       0 !NACC: acceptors",
              "", "", "       0 !NNB", "", "", "       1       0 !NGRP", "       0       0       0", ""]
    path.write_text("\n".join(lines) + "\n")


def write_pdb(path, atoms, box=30.0):
    lines = [f"CRYST1{box:9.3f}{box:9.3f}{box:9.3f}  90.00  90.00  90.00 P 1           1"]
    for i, (seg, resid, resn, name, _, _, _, (x, y, z)) in enumerate(atoms, 1):
        nm = f" {name:<3s}" if len(name) < 4 else name
        lines.append(f"ATOM  {i:5d} {nm} {resn:<4s} {resid:4d}    {x:8.3f}{y:8.3f}{z:8.3f}  1.00  "
                     f"{1.0 if resn == 'ALA' and name in ('N', 'CA', 'C', 'O') else 0.0:4.2f}      {seg:<4s}")
    lines.append("END")
    path.write_text("\n".join(lines) + "\n")


def write_gro(path, atoms, box=3.0):
    lines = ["synthetic", f"{len(atoms):5d}"]
    for i, (_, resid, resn, name, _, _, _, (x, y, z)) in enumerate(atoms, 1):
        lines.append(f"{resid:5d}{resn:<5s}{name:>5s}{i:5d}{x / 10:8.3f}{y / 10:8.3f}{z / 10:8.3f}")
    lines.append(f"{box:10.5f}{box:10.5f}{box:10.5f}")
    path.write_text("\n".join(lines) + "\n")


def make_package(root: Path, engines=("gromacs", "openmm", "namd")) -> Path:
    """Unpacked charmm-gui.tgz as the bot leaves it (common top folder stripped)."""
    root.mkdir(parents=True, exist_ok=True)
    atoms = peptide_atoms()
    (root / "input.config.dat").write_text(
        '{"systype":null,"dimensions":["30","30","30","90.0","90.0","90.0"],"input":["namd","gromacs","openmm"],'
        '"forcefield":{"type":"c36m","files":["default"],"custom":[]},"hmr":false}')
    (root / "step3_pbcsetup.str").write_text(" SET BOXTYPE  = RECT\n SET XTLTYPE  = CUBIC\n SET A = 30\n SET B = 30\n"
                                             " SET C = 30\n SET ALPHA = 90.0\n SET BETA  = 90.0\n SET GAMMA = 90.0\n"
                                             " SET POSID = SOD\n SET NEGID = CLA\n SET ZCEN  = 0\n")
    (root / "step2.2_ions_count.str").write_text("set pos = SOD\nif @IN1 .eq. 1 set conc = 0.15\n")
    (root / "toppar.str").write_text("* toppar\nopen read card unit 10 name toppar/top_all36_prot.rtf\n"
                                     "open read card unit 20 name toppar/par_all36m_prot.prm\n")
    (root / "toppar").mkdir(exist_ok=True)
    for f in ("top_all36_prot.rtf", "par_all36m_prot.prm", "toppar_water_ions.str"):
        (root / "toppar" / f).write_text("* fake\n")
    if "gromacs" in engines:
        g = root / "gromacs"
        g.mkdir()
        (g / "README").write_text(GMX_README)
        (g / "step4.0_minimization.mdp").write_text(MDP_MIN)
